fn approval_signature(key: &str, message: &str) -> String {
    // RFC 2104 HMAC; keys generated by this shell are exactly 64 ASCII bytes.
    let mut block = [0u8;64];
    let material = if key.len()>64 { Sha256::digest(key.as_bytes()).to_vec() } else { key.as_bytes().to_vec() };
    block[..material.len()].copy_from_slice(&material);
    let inner:Vec<u8>=block.iter().map(|b|b^0x36).collect();
    let outer:Vec<u8>=block.iter().map(|b|b^0x5c).collect();
    let mut hash=Sha256::new();hash.update(inner);hash.update(message.as_bytes());
    let mut result=Sha256::new();result.update(outer);result.update(hash.finalize());
    result.finalize().iter().map(|b|format!("{b:02x}")).collect()
}

