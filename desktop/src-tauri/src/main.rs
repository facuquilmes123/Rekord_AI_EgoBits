#[cfg(windows)]
fn confirm_native(summary: &str) -> bool {
    #[link(name="user32")]
    extern "system" { fn MessageBoxW(owner:*mut std::ffi::c_void,text:*const u16,title:*const u16,kind:u32)->i32; }
    let text:Vec<u16>=format!("{summary}\n\nNo abras Rekordbox hasta finalizar. ¿Confirmás esta operación?").encode_utf16().chain(Some(0)).collect();
    let title:Vec<u16>="Rekord AI · Confirmar colección real".encode_utf16().chain(Some(0)).collect();
    // YES/NO, warning, default NO. Only this trusted native command can sign.
    unsafe { MessageBoxW(std::ptr::null_mut(),text.as_ptr(),title.as_ptr(),0x04|0x30|0x100)==6 }
}
#[cfg(not(windows))]
fn confirm_native(_: &str)->bool { false }

#[tauri::command]
async fn approve_native_operation(app:tauri::AppHandle,token:String,source_revision:Option<String>)->Result<Value,String> {
    tauri::async_runtime::spawn_blocking(move || {
        let state=app.state::<BackendState>();
        let preview=local_request(&state,"POST","/api/native/approval-preview",Some(&serde_json::json!({"token":token}))).ok_or("La propuesta venció o no está disponible")?;
        let summary=preview["summary"].as_str().ok_or("Resumen inválido")?;
        let operation=preview["operation"].as_str().ok_or("Operación inválida")?;
        let digest=preview["digest"].as_str().ok_or("Propuesta inválida")?;
        let path=match operation { "restore"=>"/api/native/restore/apply", "create_playlist"=>"/api/native/apply", "consolidate_duplicates"=>"/api/duplicates/delete", "recover_transactions"=>"/api/transactions/apply", "restore_transactions"=>"/api/transactions/restore/apply", _=>return Err("Operación no admitida".into()) };
        if !confirm_native(summary) { return Ok(serde_json::json!({"state":"cancelled"})); }
        let signature=approval_signature(&state.approval_key,&format!("{operation}:{token}:{digest}"));
        let payload=serde_json::json!({"token":token,"source_revision":source_revision,"confirmed":true,"approval_digest":digest,"approval_signature":signature});
        local_request(&state,"POST",path,Some(&payload)).ok_or("Operación rechazada. Revisá el estado y los respaldos antes de volver a intentar.".into())
    }).await.map_err(|_|"No se pudo completar la confirmación".to_string())?
}

#[tauri::command]
fn drag_collection_track(app: tauri::AppHandle, state: tauri::State<'_, BackendState>, track_id:String, source_revision:String) -> Result<(),String> {
    let result=local_request(&state,"POST","/api/track/drag-file",Some(&serde_json::json!({"track_id":track_id,"source_revision":source_revision})))
        .ok_or("La pista no está disponible o la colección cambió")?;
    let path=result["path"].as_str().ok_or("Ruta de colección inválida")?.to_owned();
    let feedback=app.clone();
    app.run_on_main_thread(move || {
        use tauri::Emitter;
        match file_drag::start(&path) {
            Ok(accepted)=>{let _=feedback.emit("track-drag-result",serde_json::json!({"accepted":accepted}));},
            Err(error)=>{let _=feedback.emit("track-drag-error",error);}
        }
    }).map_err(|_| "No se pudo iniciar el arrastre".into())
}

#[tauri::command]
fn hide_recommendation_popup(app:tauri::AppHandle) {
    if let Some(window)=app.get_webview_window("recommendation") { let _=window.hide(); }
}

// Inno checks this stable name before upgrading/uninstalling. Keep the handle
// alive until the OS terminates the process, including while the tray is hidden.
#[cfg(windows)]
fn hold_upgrade_mutex() {
    #[link(name = "kernel32")]
    extern "system" {
        fn CreateMutexW(attributes: *const std::ffi::c_void, owner: i32, name: *const u16) -> *mut std::ffi::c_void;
    }
    let name: Vec<u16> = "Local\\RekordAIApp".encode_utf16().chain(Some(0)).collect();
    let handle = unsafe { CreateMutexW(std::ptr::null(), 0, name.as_ptr()) };
    assert!(!handle.is_null(), "No se pudo proteger la actualización de Rekord AI");
}

struct BackendState {
    port: u16,
    token: String,
    approval_key: String,
    child: Mutex<Child>,
    last_toast: Mutex<Option<(String, Instant)>>,
}

#[derive(Serialize)]
struct BackendInfo {
    port: u16,
    token: String,
}

#[tauri::command]
fn backend_info(state: tauri::State<'_, BackendState>) -> BackendInfo {
    BackendInfo { port: state.port, token: state.token.clone() }
}

fn local_request(state: &BackendState, method: &str, path: &str, payload: Option<&Value>) -> Option<Value> {
    let body = payload.map(Value::to_string).unwrap_or_default();
    let address: SocketAddr = format!("127.0.0.1:{}", state.port).parse().ok()?;
    let mut stream = TcpStream::connect_timeout(&address, Duration::from_millis(600)).ok()?;
    // Process discovery can take 3s; history popup may perform two probes.
    stream.set_read_timeout(Some(Duration::from_secs(if path=="/api/duplicates/delete" {900} else if path=="/api/native/apply" || path=="/api/native/restore/apply" || path=="/api/transactions/apply" || path=="/api/transactions/restore/apply" {180} else {8}))).ok()?;
    stream.set_write_timeout(Some(Duration::from_millis(1000))).ok()?;
    let request = format!(
        "{method} {path} HTTP/1.0\r\nHost: 127.0.0.1\r\nX-EgoBits-Token: {}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{}", state.token, body.len(), body
    );
    stream.write_all(request.as_bytes()).ok()?;
    let mut bytes = Vec::new();
    stream.read_to_end(&mut bytes).ok()?;
    let text = String::from_utf8(bytes).ok()?;
    let (head, body) = text.split_once("\r\n\r\n")?;
    if !head.starts_with("HTTP/1.0 200") && !head.starts_with("HTTP/1.1 200") {
        return None;
    }
    serde_json::from_str(body).ok()
}

fn local_get(state: &BackendState, path: &str) -> Option<Value> {
    local_request(state, "GET", path, None)
}

fn start_backend(app: &tauri::App) -> Result<BackendState, Box<dyn std::error::Error>> {
    let mut secret = [0u8; 32];
    OsRng.fill_bytes(&mut secret);
    let token = secret.iter().map(|byte| format!("{byte:02x}")).collect::<Vec<_>>().join("");
    OsRng.fill_bytes(&mut secret);
    let approval_key=secret.iter().map(|byte|format!("{byte:02x}")).collect::<String>();
    let backend_path = std::env::current_exe()?.with_file_name("egobits-backend.exe");
    let resource_root = app.path().resource_dir()?;
    let mut command = Command::new(backend_path);
    command.args(["--serve", "--port", "0"])
        .env("EGB_SESSION_TOKEN", &token)
        .env("EGB_NATIVE_APPROVAL_KEY", &approval_key)
        .env("EGB_RESOURCE_ROOT", resource_root)
        .stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::null());
    #[cfg(windows)] {
        use std::os::windows::process::CommandExt;
        command.creation_flags(0x08000000);
    }
    let mut child = command.spawn()?;
    let stdout = child.stdout.take().ok_or("Backend sin stdout")?;
    let (sender, receiver) = mpsc::channel();
    thread::spawn(move || {
        for line in BufReader::new(stdout).lines().map_while(Result::ok) {
            if let Some(port) = line.strip_prefix("EGB_READY:").and_then(|value| value.parse::<u16>().ok()) {
                let _ = sender.send(port);
            }
        }
    });
    let port = match receiver.recv_timeout(Duration::from_secs(30)) {
        Ok(port) if port > 0 => port,
        _ => { let _ = child.kill(); let _ = child.wait(); return Err("El servicio local no inició".into()); }
    };
    Ok(BackendState { port, token, approval_key, child: Mutex::new(child), last_toast: Mutex::new(None) })
}

fn main() {
    #[cfg(windows)]
    hold_upgrade_mutex();
    let app = tauri::Builder::default()
        .plugin(tauri_plugin_notification::init())
        .invoke_handler(tauri::generate_handler![backend_info,drag_collection_track,hide_recommendation_popup,approve_native_operation])
        .setup(|app| {
            let backend = start_backend(app)?;
            app.manage(backend);
            let popup=tauri::WebviewWindowBuilder::new(app,"recommendation",tauri::WebviewUrl::App("live-popup.html".into()))
                .title("Rekord AI · Próximas pistas").inner_size(440.0,390.0)
                .visible(false).focused(false).always_on_top(true).resizable(false).skip_taskbar(true).build()?;
            if let (Ok(Some(monitor)),Ok(size))=(popup.current_monitor(),popup.outer_size()) {
                let area=monitor.work_area();
                let x=area.position.x+(area.size.width.saturating_sub(size.width+16)) as i32;
                let y=area.position.y+(area.size.height.saturating_sub(size.height+16)) as i32;
                let _=popup.set_position(tauri::PhysicalPosition::new(x,y));
            }

            let show = MenuItem::with_id(app, "show", "Mostrar/Ocultar ventana", true, None::<&str>)?;
            let silence = MenuItem::with_id(app, "silence", "Modo Silencio: desactivado", true, None::<&str>)?;
            let push = MenuItem::with_id(app, "push", "Activar notificaciones", true, None::<&str>)?;
            let current = MenuItem::with_id(app,"current","Mostrar recomendación actual",true,None::<&str>)?;
            let exit = MenuItem::with_id(app, "exit", "Salir", true, None::<&str>)?;
            let menu = Menu::with_items(app, &[&show, &current, &silence, &push, &exit])?;
            TrayIconBuilder::with_id("main")
                .icon(tauri::include_image!("./icons/rekord-ia-tray.png"))
                .tooltip("Rekord AI · Rekordbox: desconocido")
                .menu(&menu)
                .on_menu_event(move |handle, event| {
                    let state = handle.state::<BackendState>();
                    match event.id().as_ref() {
                        "current" => {
                            if let Some(value)=local_get(&state,"/api/recommendation-popup") {
                                if value["display"].as_bool()==Some(true) {
                                    if let Some(window)=handle.get_webview_window("recommendation") {
                                        use tauri::Emitter;
                                        let _=window.emit("recommendation-update",&value);
                                        let _=window.show();
                                    }
                                } else if let Some(window)=handle.get_webview_window("main") {
                                    use tauri::Emitter;
                                    let _=window.show();
                                    let _=window.set_focus();
                                    let _=window.emit("recommendation-needs-setup",&value);
                                }
                            } else if let Some(window)=handle.get_webview_window("main") {
                                use tauri::Emitter;
                                let _=window.show();
                                let _=window.set_focus();
                                let _=window.emit("recommendation-needs-setup",serde_json::json!({"reason":"No se pudo consultar el seguimiento. Revisá la conexión de Rekord AI."}));
                            }
                        }
                        "show" => {
                            if let Some(window) = handle.get_webview_window("main") {
                                if window.is_visible().unwrap_or(false) {
                                    let _ = window.hide();
                                } else {
                                    let _ = window.show();
                                    let _ = window.set_focus();
                                }
                            }
                        }
                        "silence" | "push" => {
                            if let Some(settings) = local_get(&state, "/api/settings") {
                                let key = if event.id().as_ref() == "silence" { "silenced" } else { "enabled" };
                                let active = !settings["notifications"][key].as_bool().unwrap_or(false);
                                let mut notification = serde_json::Map::new();
                                notification.insert(key.into(), Value::Bool(active));
                                let payload = serde_json::json!({"notifications": notification});
                                let _ = local_request(&state, "POST", "/api/settings", Some(&payload));
                            }
                        }
                        "exit" => handle.exit(0),
                        _ => {}
                    }
                })
                .build(app)?;

            let handle = app.handle().clone();
            let popup_event=Mutex::new(None::<(String,Instant)>);
            thread::spawn(move || loop {
                let state = handle.state::<BackendState>();
                if state.child.lock().map(|mut child| child.try_wait().ok().flatten().is_some()).unwrap_or(true) {
                    break;
                }
                let status = local_get(&state, "/api/status");
                let rb_state = status.as_ref()
                    .and_then(|json| json.get("rekordbox_state"))
                    .and_then(Value::as_str).unwrap_or("unknown");
                if let Some(tray) = handle.tray_by_id("main") {
                    let _ = tray.set_tooltip(Some(format!("Rekord AI · Rekordbox: {rb_state}")));
                }
                let notifications = status.as_ref().and_then(|value| value.get("notifications"));
                let enabled = notifications.and_then(|value| value["enabled"].as_bool()).unwrap_or(false);
                let muted = notifications.and_then(|value| value["silenced"].as_bool()).unwrap_or(true);
                let frequency = notifications.and_then(|value| value["min_frequency_seconds"].as_u64()).unwrap_or(30);
                let _ = silence.set_text(if muted { "Modo Silencio: activado" } else { "Modo Silencio: desactivado" });
                let _ = push.set_text(if enabled { "Desactivar notificaciones" } else { "Activar notificaciones" });
                if let Some(window)=handle.get_webview_window("recommendation") {
                    if let Some(value)=local_get(&state,"/api/recommendation-popup") {
                        let display=value["display"].as_bool().unwrap_or(false);
                        if !display { 
                            let _=window.hide();
                            *popup_event.lock().unwrap()=None;
                            use tauri::Emitter;
                            let _=window.emit("recommendation-update",&value);
                        }
                        else if let Some(event)=value["event_id"].as_str() {
                            // Popup delivery has independent throttling from native Toasts.
                            use tauri::Emitter;
                            let mut last=popup_event.lock().unwrap();
                            let eligible=last.as_ref().map(|(id,when):&(String,Instant)|id!=event && when.elapsed()>=Duration::from_secs(frequency)).unwrap_or(true);
                            if eligible {
                                let _=window.emit("recommendation-update",&value);
                                let _=window.show();
                                *last=Some((event.to_owned(),Instant::now()));
                            }
                        }
                    } else { let _=window.hide(); }
                }
                if rb_state == "open" && enabled && !muted && status.as_ref().and_then(|value|value["telemetry_available"].as_bool())==Some(true) {
                    if let Some(suggestion) = local_get(&state, "/api/live-suggestion") {
                        if suggestion.get("confirmed").and_then(Value::as_bool) == Some(true) {
                            let event_id = suggestion.get("event_id").and_then(Value::as_str).unwrap_or("");
                            let title = suggestion.get("title").and_then(Value::as_str).unwrap_or("");
                            let body = suggestion.get("body").and_then(Value::as_str).unwrap_or("");
                            if !event_id.is_empty() && !body.is_empty() {
                                if let Ok(mut last) = state.last_toast.lock() {
                                    let eligible = last.as_ref().map(|(id, when)| id != event_id && when.elapsed() >= Duration::from_secs(frequency)).unwrap_or(true);
                                    if eligible {
                                        let permission = handle.notification().permission_state();
                                        let permission = match permission {
                                            Ok(PermissionState::Prompt | PermissionState::PromptWithRationale) => handle.notification().request_permission(),
                                            other => other,
                                        };
                                        if matches!(permission, Ok(PermissionState::Granted)) {
                                            if handle.notification().builder().title(title).body(body).show().is_ok() {
                                                *last = Some((event_id.to_owned(), Instant::now()));
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
                thread::sleep(Duration::from_secs(3));
            });
            Ok(())
        })
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                api.prevent_close();
                let _ = window.hide();
            }
        })
        .build(tauri::generate_context!())
        .expect("No se pudo iniciar Rekord AI");

    app.run(|handle, event| {
        if let tauri::RunEvent::ExitRequested { api, .. } = &event {
            let state = handle.state::<BackendState>();
            // The backend accepts shutdown under the same native operation lock
            // and rejects queued/new writes after accepting it.
            let accepted = local_request(&state, "POST", "/api/shutdown", None).is_some();
            let running = state.child.lock().map(|mut child| child.try_wait().ok().flatten().is_none()).unwrap_or(true);
            if !accepted && running {
                api.prevent_exit();
                if let Some(window) = handle.get_webview_window("main") { let _ = window.show(); let _ = window.set_focus(); }
                return;
            }
        }
        if let tauri::RunEvent::Exit = event {
            let state = handle.state::<BackendState>();
            let _ = local_request(&state, "POST", "/api/shutdown", None);
            if let Ok(mut child) = state.child.lock() {
                for _ in 0..60 {
                    if child.try_wait().ok().flatten().is_some() { return; }
                    thread::sleep(Duration::from_millis(200));
                }
                #[cfg(windows)] {
                    use std::os::windows::process::CommandExt;
                    let _ = Command::new("taskkill.exe").args(["/PID", &child.id().to_string(), "/T", "/F"])
                        .creation_flags(0x08000000).stdout(Stdio::null()).stderr(Stdio::null()).status();
                }
                let _ = child.kill();
                let _ = child.wait();
            };
        }
    });
}
