"""Bounded collection grounding for open-ended answers; data, never instructions."""
from collections import Counter
import json
import re
from ..ai.parser import sanitize_user_input
from ..core.models import PlanningError


def collection_context(lib, query, reference=None):
    if lib is None: return {'collection':None,'limitations':['No hay una colección legible cargada.']}
    tracks=list(lib.tracks.values())
    words=[w for w in re.findall(r'\w+',query.casefold()) if len(w)>=3 and w not in {'pistas','canciones','coleccion','rekordbox','playlist','playlists','como','para','tengo','puedo','cuales','una','que','mis','las','los','del'}]
    hits=[]
    if reference and reference.get('source_revision')==lib.revision and reference.get('track_id') in lib.tracks:
        hits.append(lib.tracks[reference['track_id']])
    for t in tracks:
        if words and any(w in f'{t.artist} {t.title}'.casefold() for w in words) and t not in hits:
            hits.append(t)
        if len(hits)>=4: break
    bpms=[t.bpm for t in tracks if t.bpm is not None]
    ctx={'collection':{'tracks':len(tracks),'playlists':len(lib.playlists),
         'missing_bpm':sum(t.bpm is None for t in tracks),'missing_key':sum(not t.key for t in tracks),
         'missing_genre':sum(not t.genre for t in tracks),
         'verified_energy':sum(t.energy is not None and bool(t.energy_source) for t in tracks),
         'bpm_range':[min(bpms),max(bpms)] if bpms else None},
         'top_genres':[(name[:60],count) for name,count in Counter(t.genre or 'Sin género' for t in tracks).most_common(5)],
         'top_artists':[(name[:60],count) for name,count in Counter(t.artist or 'Sin artista' for t in tracks).most_common(5)],
         'largest_playlists':[{'name':name[:70],'tracks':len(ids)} for name,ids in sorted(lib.playlists.items(),key=lambda item:(-len(item[1]),item[0]))[:3]],
         'playlist_sample':[{'name':name[:70],'tracks':len(ids)} for name,ids in list(lib.playlists.items())[:8]],
         'track_sample':[{'id':t.id,'title':t.title[:60],'artist':t.artist[:40],'genre':t.genre[:35],
                          'bpm':t.bpm,'key':t.key,'energy':t.energy if t.energy_source else None} for t in hits],
         'source_kind':getattr(lib,'source_kind','xml'),
         'limitations':['Los conteos de collection cubren toda la colección conectada; sólo track_sample y playlist_sample son muestras.',
                        ('La base viva se lee en una transacción de sólo lectura; no informa el audio actual.' if getattr(lib,'source_kind','xml')=='native_snapshot' else 'El XML puede diferir de cambios posteriores en Rekordbox; no informa el audio actual.'),
                        'Energía con fuente acoustic-v1 es un índice heurístico estimado; LUFS mide sonoridad, no energía musical científica.',
                        'No se ejecutaron acciones con esta respuesta.'],
         'available_workflows':['Buscar/parecidos/comparar/auditar/planificar; exportar XML/M3U8.',
             'Herramientas DJ: base viva, MyTags/estrellas/reproducciones, cues/frases, análisis acústico local, Key Shift opcional, USB respaldado y conexión Pro DJ Link.',
             'Crear playlist nativa, cierre asistido y restauración desde Configuración con revisión y respaldo.',
             'Duplicados idénticos: revisión, respaldo, cierre de Rekordbox, consolidación recuperable y restauración. Master audible no certificado.']}
    # Keep prompt within the existing local runtime's context budget.
    while len(json.dumps(ctx,ensure_ascii=False))>3000:
        if ctx['track_sample']: ctx['track_sample'].pop()
        elif ctx['playlist_sample']: ctx['playlist_sample'].pop()
        else: break
    return ctx


def validate_answer(payload, context):
    if not isinstance(payload,dict) or set(payload)!={'answer','suggested_questions','track_ids'}:
        raise PlanningError('Respuesta conversacional de IA inválida.')
    answer=payload['answer']
    questions=payload['suggested_questions']; ids=payload['track_ids']
    if not isinstance(answer,str) or not answer.strip() or len(answer)>6000:
        raise PlanningError('La IA no devolvió una respuesta legible.')
    if not isinstance(questions,list) or len(questions)>3 or any(not isinstance(q,str) or not q.strip() or len(q)>200 for q in questions):
        raise PlanningError('Preguntas sugeridas de IA inválidas.')
    allowed={t['id'] for t in context.get('track_sample',[])}
    if not isinstance(ids,list) or len(ids)>4 or any(not isinstance(i,str) or i not in allowed for i in ids):
        raise PlanningError('La IA citó pistas fuera del contexto verificado.')
    if any(i not in allowed for i in re.findall(r'@id:([^\s,;.)]+)',answer)):
        raise PlanningError('La IA mencionó una referencia de pista no verificada.')
    # Catch contradictory capability/metadata claims observed in real local inference.
    # This is a bounded guard, not proof of every statement generated by an LLM.
    folded=answer.casefold()
    if re.search(r'ignor[aáe].{0,35}instrucciones|(?:abr[ií]|ejecut[aá]|run|execute).{0,40}(?:powershell|cmd\.exe|terminal|curl|wget)|(?:desactiv[aá]|disable).{0,40}(?:defender|antivirus)', '\n'.join([answer,*questions]), re.I):
        raise PlanningError('La IA devolvió instrucciones externas no admitidas.')
    facts=context.get('collection')
    if facts and re.search(r'(?:datos|conteos|estad[ií]sticas|auditor[ií]a)[^.!?\n]{0,75}(?:parciales|muestra|acceso al master|base de datos completa)|(?:muestras limitadas)[^.!?\n]{0,75}(?:colecci[oó]n completa|datos parciales)',folded):
        raise PlanningError('La IA confundió una muestra de pistas con los conteos completos del XML.')
    if re.search(r'\b(?:library|playlist|track|setlist|system)\.[a-z_]+\b|\b(?:count|mode|same_genre|harmonic)\s*=',folded):
        raise PlanningError('La IA expuso herramientas internas en vez de una orientación para el DJ.')
    if facts and facts['missing_key']==0 and re.search(r'(?:no (?:ten[eé]s|tienes|hay)|sin|faltan)[^.!?\n]{0,65}(?:tonalidad|teclas|\bkey\b)',folded):
        raise PlanningError('La IA contradijo las tonalidades verificadas.')
    if facts and facts['missing_bpm']==0 and re.search(r'(?:no (?:ten[eé]s|tienes|hay)|sin|faltan)[^.!?\n]{0,65}\bbpm\b',folded):
        raise PlanningError('La IA contradijo los BPM verificados.')
    if re.search(r'(?:faltan?|necesit\w*|requi\w*)[^.!?\n]{0,60}tonalidad[^.!?\n]{0,60}(?:calcular|evaluar)[^.!?\n]{0,20}energ[ií]a|energ[ií]a[^.!?\n]{0,40}(?:necesit\w*|requi\w*)[^.!?\n]{0,60}\bmaster\b',folded):
        raise PlanningError('La IA inventó una dependencia para la energía: exige valores con fuente, no master ni tonalidad.')
    if re.search(r'(?:b[uú]squeda|buscar|auditor[ií]a)[^.!?\n]{0,60}(?:requiere|necesita|sin)[^.!?\n]{0,30}confirmaci[oó]n',folded):
        raise PlanningError('La IA inventó un requisito para operaciones de lectura.')
    if re.search(r'(?:he|ya|acabo de)\s+(?:borrado|eliminado|creado|modificado|cerrado|restaurado)',folded):
        raise PlanningError('La IA afirmó una acción que no se ejecutó.')
    verified=''
    if facts:
        verified=(f"Datos comprobados del XML: {facts['tracks']} pistas · {facts['playlists']} playlists.\n"
                  f"Metadatos faltantes: BPM {facts['missing_bpm']} · tonalidad {facts['missing_key']} · género {facts['missing_genre']}. "
                  f"Energía con fuente: {facts['verified_energy']} pistas.\n\n")
    return {'response':verified+'Orientación del asistente local:\n'+sanitize_user_input(answer,6000), 'applied':False, 'answer_mode':'local_assistant',
            'verified_facts':facts,
            'grounding':'XML de la colección cargada y conocimiento del modelo offline',
            'suggestions':[{'label':q,'query':q} for q in questions], 'referenced_track_ids':ids}


def fallback_answer(query, context, reason='unavailable'):
    facts=context.get('collection')
    summary='No hay una colección cargada; cargá el XML para consultar tus pistas.'
    if facts:
        summary=(f"Puedo consultar tu XML: {facts['tracks']} pistas y {facts['playlists']} playlists. "
                 f"Faltan BPM en {facts['missing_bpm']}, tonalidad en {facts['missing_key']} y género en {facts['missing_genre']} pistas. "
                 f"Hay energía con fuente en {facts['verified_energy']} pistas.")
    return {'response':'El modelo local no completó esta consulta. '+summary+
            '\nPodés consultar pistas pendientes de análisis, buscar canciones, auditar la colección o preparar un set. Para esta pregunta abierta necesito que la IA vuelva a estar disponible. No se modificaron datos.',
            'applied':False,'answer_mode':'guided_fallback','verified_facts':facts,'model_failure':reason,
            'suggestions':[{'label':'Reintentar mi pregunta','query':sanitize_user_input(query,200)},
                           {'label':'Ver estado de la IA local','tab':'tab-config','target':'config-llm'},
                           {'label':'Revisar pistas pendientes de análisis','query':'cuales pistas me faltan analizar en rekordbox?'}]}
